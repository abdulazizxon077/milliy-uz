export function translatePrice(price, lang = 'uz') {
  if (!price || lang === 'uz') return price;
  let res = String(price);
  if (res.toLowerCase().includes('bepul')) {
    return lang === 'ru' ? 'Бесплатно' : lang === 'en' ? 'Free' : 'Bepul';
  }
  if (res.includes(' dan')) {
    if (lang === 'ru') res = 'от ' + res.replace(' dan', '');
    else if (lang === 'en') res = 'from ' + res.replace(' dan', '');
  }
  return res;
}
